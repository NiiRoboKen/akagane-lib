from pathlib import Path
import fnmatch
import os
import sys

ROOT = Path("src").resolve()
OUTPUT = ROOT / "akagane.hpp"
IGNORE_FILE = Path(".includeignore").resolve()

BEGIN = "// generated by scripts/gen_include.py start."
END = "// generated by scripts/gen_include.py end."


def load_ignore_patterns():
    if not IGNORE_FILE.exists():
        return []

    patterns = []
    for line in IGNORE_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            patterns.append(line.replace("\\", "/"))
    return patterns


def is_ignored(path, patterns):
    relative = path.relative_to(ROOT).as_posix()

    for pattern in patterns:
        pattern = pattern.lstrip("/")

        if pattern.endswith("/"):
            directory = pattern.rstrip("/")
            if relative == directory or relative.startswith(directory + "/"):
                return True

        if fnmatch.fnmatchcase(relative, pattern):
            return True

        if "/" not in pattern and fnmatch.fnmatchcase(
            path.name, pattern
        ):
            return True

        if pattern.startswith("**/"):
            if fnmatch.fnmatchcase(relative, pattern[3:]):
                return True

    return False


def generate_include_lines():
    patterns = load_ignore_patterns()

    headers = sorted(
        path for path in ROOT.rglob("*.hpp")
        if path.resolve() != OUTPUT
        and not is_ignored(path, patterns)
    )

    return [
        f'#include "{path.relative_to(ROOT).as_posix()}"'
        for path in headers
    ]


def update_header():
    if not ROOT.is_dir():
        raise FileNotFoundError(f"Include directory not found: {ROOT}")

    if not OUTPUT.exists():
        OUTPUT.write_text(
            f"#pragma once\n\n{BEGIN}\n{END}\n",
            encoding="utf-8",
        )

    original = OUTPUT.read_text(encoding="utf-8")

    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError(
            f"{OUTPUT} must contain exactly one BEGIN and END marker"
        )

    begin_pos = original.index(BEGIN) + len(BEGIN)
    end_pos = original.index(END)

    if begin_pos > end_pos:
        raise ValueError("BEGIN marker must appear before END marker")

    generated = "\n"
    lines = generate_include_lines()
    if lines:
        generated += "\n".join(lines) + "\n"

    updated = original[:begin_pos] + generated + original[end_pos:]

    if updated != original:
        OUTPUT.write_text(updated, encoding="utf-8")
        print(f"Updated: {OUTPUT}")
    else:
        print(f"No changes: {OUTPUT}")


if __name__ == "__main__":
    try:
        update_header()
    except (OSError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        sys.exit(1)
